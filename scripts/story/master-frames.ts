function slotTypeFor(key: string): SlotType {
  if (key.startsWith("person")) return "person";
  if (key.startsWith("place")) return "place";
  if (key.startsWith("object")) return "object";
  if ((SLOT_TYPES as readonly string[]).includes(key)) return key as SlotType;
  throw new Error(`Unknown slot key ${key}`);
}

for (const frame of MASTER_FRAMES) {
  const keys = [...frame.translation.en.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((match) => match[1]);
  frame.slots = Object.fromEntries(keys.map((key) => [key, slotTypeFor(key)]));
  // World lexemes already carry their article ("the bookstore"), so master
  // translations must not add a second one before object/place/person slots.
  frame.translation.en = frame.translation.en.replace(
    /\b[Tt]he (?=\{(?:object|place|person))/g,
    "",
  );
  frame.translation.id = frame.translation.id.replace(
    /\b[Tt]he (?=\{(?:object|place|person))/g,
    "",
  );
}

export const MASTER_FRAME_BY_ID = new Map(
  MASTER_FRAMES.map((frame) => [frame.id, frame]),
);
